import { defineConfig, type DatabaseTarget, type PgBouncerConfig, type PgBouncerConfigInput, type TlsSide } from "./config";

const bool = (v: boolean) => (v ? "1" : "0");
/** libpq-style value for a [databases] connection string. */
const connValue = (v: string | number) => {
  const s = String(v);
  return /^[A-Za-z0-9_.:-]+$/.test(s) ? s : `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
};

function databaseLine(d: DatabaseTarget): string {
  const parts: [string, string | number | undefined][] = [
    ["host", d.host],
    ["port", d.port ?? 5432],
    ["dbname", d.dbname ?? (d.name === "*" ? undefined : d.name)],
    ["user", d.user],
    ["auth_user", d.authUser],
    ["pool_mode", d.poolMode],
    ["pool_size", d.poolSize],
    ["min_pool_size", d.minPoolSize],
    ["reserve_pool", d.reservePoolSize],
    ["max_db_connections", d.maxDbConnections],
  ];
  return `${d.name} = ${parts.filter(([, v]) => v !== undefined).map(([k, v]) => `${k}=${connValue(v!)}`).join(" ")}`;
}

function tlsLines(prefix: "client" | "server", t: TlsSide): string[] {
  const out = [`${prefix}_tls_sslmode = ${t.mode}`];
  if (t.certFile) out.push(`${prefix}_tls_cert_file = ${t.certFile}`);
  if (t.keyFile) out.push(`${prefix}_tls_key_file = ${t.keyFile}`);
  if (t.caFile) out.push(`${prefix}_tls_ca_file = ${t.caFile}`);
  if (t.protocols) out.push(`${prefix}_tls_protocols = ${t.protocols}`);
  if (t.ciphers) out.push(`${prefix}_tls_ciphers = ${t.ciphers}`);
  return out;
}

/**
 * Renders pgbouncer.ini. Takes a full config or the input to `defineConfig` (checked either way).
 * The file holds no passwords; they live in the userlist (`renderUserlist`).
 */
export function renderIni(config: PgBouncerConfig | PgBouncerConfigInput): string {
  const c = defineConfig(config);
  const a = c.auth;
  const lines = [
    "; Generated by @mgpl-diagnostics/pgbouncer-kit. Edit the configuration, not this file.",
    "",
    "[databases]",
    ...c.databases.map(databaseLine),
    "",
    "[pgbouncer]",
    `listen_addr = ${c.listenAddr}`,
    `listen_port = ${c.listenPort}`,
    "",
    `auth_type = ${a.type}`,
    `auth_file = ${a.file}`,
    ...(a.query ? [`auth_query = ${a.query}`] : []),
    ...(a.user ? [`auth_user = ${a.user}`] : []),
    ...(a.dbname ? [`auth_dbname = ${a.dbname}`] : []),
    ...(a.hbaFile ? [`auth_hba_file = ${a.hbaFile}`] : []),
    ...(c.adminUsers.length ? [`admin_users = ${c.adminUsers.join(", ")}`] : []),
    ...(c.statsUsers.length ? [`stats_users = ${c.statsUsers.join(", ")}`] : []),
    "",
    `pool_mode = ${c.poolMode}`,
    `max_client_conn = ${c.maxClientConn}`,
    `default_pool_size = ${c.defaultPoolSize}`,
    `min_pool_size = ${c.minPoolSize}`,
    `reserve_pool_size = ${c.reservePoolSize}`,
    `reserve_pool_timeout = ${c.reservePoolTimeout}`,
    `max_db_connections = ${c.maxDbConnections}`,
    `max_prepared_statements = ${c.maxPreparedStatements}`,
    "",
    `server_reset_query = ${c.serverResetQuery}`,
    `server_lifetime = ${c.serverLifetime}`,
    `server_idle_timeout = ${c.serverIdleTimeout}`,
    `server_connect_timeout = ${c.serverConnectTimeout}`,
    `query_wait_timeout = ${c.queryWaitTimeout}`,
    `client_idle_timeout = ${c.clientIdleTimeout}`,
    `idle_transaction_timeout = ${c.idleTransactionTimeout}`,
    ...(c.ignoreStartupParameters.length ? [`ignore_startup_parameters = ${c.ignoreStartupParameters.join(",")}`] : []),
    "",
    ...tlsLines("client", c.clientTls),
    ...tlsLines("server", c.serverTls),
    "",
    `log_connections = ${bool(c.logConnections)}`,
    `log_disconnections = ${bool(c.logConnections)}`,
    `log_pooler_errors = ${bool(c.logPoolerErrors)}`,
  ];
  const extra = Object.entries(c.extra);
  if (extra.length) lines.push("", ...extra.map(([k, v]) => `${k} = ${typeof v === "boolean" ? bool(v) : v}`));
  return `${lines.join("\n")}\n`;
}
