import { PgBouncerError } from "./errors";

/**
 * Pinned image (Alpine, runs as `postgres`, ships `pg_isready`). It uses a mounted
 * /etc/pgbouncer/pgbouncer.ini as it is; do not also set its DATABASE_URL variables.
 */
export const DEFAULT_IMAGE = "edoburu/pgbouncer:v1.25.2-p0";

export interface ComposeOptions {
  /** Service name. Default `pgbouncer`. */
  name?: string;
  /** Default `DEFAULT_IMAGE`. */
  image?: string;
  /** PgBouncer's `listenPort`. Default 6432. */
  port?: number;
  /** Host folder holding pgbouncer.ini and userlist.txt (from `mgpl-pgbouncer render`). Default `./pgbouncer`. */
  configDir?: string;
  /** Host folder with TLS files, mounted read-only at /etc/pgbouncer/tls. */
  tlsDir?: string;
  /**
   * Publish the port on the host, e.g. `"127.0.0.1:6432"`. Default: not published, so only
   * services on the same compose network reach it.
   */
  publish?: string;
  /** Services to wait for (healthy). Default `["postgres"]`; `[]` for a managed database. */
  dependsOn?: string[];
  /** Compose networks to join. */
  networks?: string[];
  /** Default `unless-stopped`. */
  restart?: string;
}

export interface ComposeService {
  image: string;
  restart: string;
  volumes: string[];
  ports?: string[];
  depends_on?: Record<string, { condition: "service_healthy" }>;
  networks?: string[];
  healthcheck: { test: string[]; interval: string; timeout: string; retries: number; start_period: string };
}

const NAME = /^[a-z0-9][a-z0-9_.-]*$/;

/** The compose service definition, as an object (merge it into your own file however you like). */
export function composeService(opts: ComposeOptions = {}): { name: string; service: ComposeService } {
  const name = opts.name ?? "pgbouncer";
  const port = opts.port ?? 6432;
  const dir = opts.configDir ?? "./pgbouncer";
  for (const n of [name, ...(opts.dependsOn ?? []), ...(opts.networks ?? [])]) {
    if (!NAME.test(n)) throw new PgBouncerError("PGBOUNCER_BAD_CONFIG", `"${n}" is not a valid compose service or network name`);
  }
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new PgBouncerError("PGBOUNCER_BAD_CONFIG", "port must be 1-65535");
  if (opts.publish !== undefined && !/^(\d{1,3}(\.\d{1,3}){3}:)?\d{1,5}$/.test(opts.publish)) {
    throw new PgBouncerError("PGBOUNCER_BAD_CONFIG", 'publish must be "<host port>" or "<ip>:<host port>"');
  }
  // eslint-disable-next-line no-control-regex
  const bad = (v: string | undefined, colon: boolean) => v !== undefined && (!v || /[\u0000-\u0020\u007f]/.test(v) || (colon && v.includes(":")));
  if (bad(opts.image, false) || bad(opts.restart, true)) throw new PgBouncerError("PGBOUNCER_BAD_CONFIG", "image and restart must be single words");
  if (bad(opts.configDir, true) || bad(opts.tlsDir, true)) throw new PgBouncerError("PGBOUNCER_BAD_CONFIG", "configDir and tlsDir must be paths without spaces or colons");
  const service: ComposeService = {
    image: opts.image ?? DEFAULT_IMAGE,
    restart: opts.restart ?? "unless-stopped",
    volumes: [
      `${dir}/pgbouncer.ini:/etc/pgbouncer/pgbouncer.ini:ro`,
      `${dir}/userlist.txt:/etc/pgbouncer/userlist.txt:ro`,
      ...(opts.tlsDir ? [`${opts.tlsDir}:/etc/pgbouncer/tls:ro`] : []),
    ],
    healthcheck: {
      test: ["CMD", "pg_isready", "-h", "127.0.0.1", "-p", String(port)],
      interval: "5s",
      timeout: "3s",
      retries: 10,
      start_period: "5s",
    },
  };
  if (opts.publish) service.ports = [`${opts.publish}:${port}`];
  const deps = opts.dependsOn ?? ["postgres"];
  if (deps.length) service.depends_on = Object.fromEntries(deps.map((d) => [d, { condition: "service_healthy" as const }]));
  if (opts.networks?.length) service.networks = [...opts.networks];
  return { name, service };
}

function yaml(value: unknown, indent: number): string {
  const pad = "  ".repeat(indent);
  if (Array.isArray(value)) return value.map((v) => `\n${pad}- ${scalar(v)}`).join("");
  if (value && typeof value === "object") {
    return Object.entries(value)
      .map(([k, v]) => (v && typeof v === "object" ? `\n${pad}${k}:${yaml(v, indent + 1)}` : `\n${pad}${k}: ${scalar(v)}`))
      .join("");
  }
  return ` ${scalar(value)}`;
}
const scalar = (v: unknown) => (typeof v === "number" ? String(v) : JSON.stringify(String(v)));

/** The service as a docker-compose YAML fragment (`services:` block), ready to save or paste. */
export function renderCompose(opts: ComposeOptions = {}): string {
  const { name, service } = composeService(opts);
  return `# Generated by @mgpl-diagnostics/pgbouncer-kit\nservices:\n  ${name}:${yaml(service, 2)}\n`;
}
